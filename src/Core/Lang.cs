        public static void Load()
        {
            try
            {
                using (var k = Registry.CurrentUser.OpenSubKey(RegKey))
                    Russian = k != null && string.Equals(k.GetValue("Language") as string, "ru", StringComparison.OrdinalIgnoreCase);
            }
            catch { Russian = false; }
            Settings.Load();
        }

